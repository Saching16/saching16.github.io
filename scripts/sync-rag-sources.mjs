import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PDFParse } from "pdf-parse";
import { REPO_SOURCES } from "../data/repos/config.js";
import { overviewBody, projectSourceLabel } from "./lib/repoOverview.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const ragDir = path.join(repoRoot, "data", "rag");
const sourcesPath = path.join(ragDir, "sources.js");

const sourceFiles = {
  resumePdf: path.join(ragDir, "resume.pdf"),
  resumeText: path.join(ragDir, "resume.txt"),
  linkedinText: path.join(ragDir, "linkedin.txt"),
  linkedinPdf: path.join(ragDir, "linkedin.pdf"),
  researchInterests: path.join(ragDir, "research-interests.md"),
};

function cleanText(rawText) {
  return rawText
    .replace(/\u0000/g, " ")
    .replace(/--\s*\d+\s+of\s+\d+\s*--/g, " ")
    .replace(/\r\n/g, "\n")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

async function readTextIfExists(filePath) {
  if (!existsSync(filePath)) {
    return "";
  }

  const content = await readFile(filePath, "utf8");
  return cleanText(content);
}

async function readPdfIfExists(filePath) {
  if (!existsSync(filePath)) {
    return "";
  }

  const data = await readFile(filePath);
  const parser = new PDFParse({ data });
  try {
    const result = await parser.getText();
    return cleanText(result.text || "");
  } finally {
    await parser.destroy();
  }
}

async function firstNonEmpty(readers) {
  for (const reader of readers) {
    const text = await reader();
    if (text) {
      return text;
    }
  }

  return "";
}

function renderSourceFile(sources) {
  return `// Generated by scripts/sync-rag-sources.mjs.
// Edit data/rag/resume.pdf, data/rag/linkedin.pdf, data/rag/research-interests.md, or a repo overview, then run npm run sync-rag.

export const RAG_SOURCES = ${JSON.stringify(sources, null, 2)};
`;
}

async function overviewSources() {
  const sources = [];

  for (const source of REPO_SOURCES) {
    const overviewPath = path.join(
      repoRoot,
      "data",
      "repos",
      source.slug,
      "overview.md",
    );
    const content = await readTextIfExists(overviewPath);
    if (!content) {
      console.warn(
        `No overview for ${source.slug}. Run npm run build-repo-overview.`,
      );
      continue;
    }

    sources.push({
      label: projectSourceLabel(source),
      content: overviewBody(content),
    });
  }

  return sources;
}

async function main() {
  const sources = [
    {
      label: "Resume",
      content: await firstNonEmpty([
        () => readPdfIfExists(sourceFiles.resumePdf),
        () => readTextIfExists(sourceFiles.resumeText),
      ]),
    },
    {
      label: "LinkedIn",
      content: await firstNonEmpty([
        () => readPdfIfExists(sourceFiles.linkedinPdf),
        () => readTextIfExists(sourceFiles.linkedinText),
      ]),
    },
    {
      label: "Research Interests",
      content: await readTextIfExists(sourceFiles.researchInterests),
    },
    ...(await overviewSources()),
  ].filter((source) => source.content.length > 0);

  const missingLabels = ["Resume", "Research Interests"].filter(
    (label) => !sources.some((source) => source.label === label),
  );

  if (missingLabels.length > 0) {
    throw new Error(
      `Missing required RAG source content: ${missingLabels.join(", ")}`,
    );
  }

  await mkdir(ragDir, { recursive: true });
  await writeFile(sourcesPath, renderSourceFile(sources), "utf8");
  console.log(`Wrote ${sources.length} RAG sources to ${sourcesPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
